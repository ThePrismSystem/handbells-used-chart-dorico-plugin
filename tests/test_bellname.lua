-- Ported from the Sibelius plugin's test/TestBellName.mss and test/TestPitch.mss, plus Dorico spelling cases.
local bellname = require("hbuc.bellname")
local constants = require("hbuc.constants")

return {
  bell_names = function(t)
    local c5 = bellname.nameOf(72, 35)
    t:eq(c5.name, "C5", "C5 name")
    t:eq(c5.letter, "C", "C5 letter")
    t:eq(c5.alter, 0, "C5 alter")
    t:eq(c5.octave, 5, "C5 octave")
    local gs5 = bellname.nameOf(80, 39)
    t:eq(gs5.name, "G#5", "G sharp 5 name")
    t:eq(gs5.alter, 1, "G sharp 5 alter")
    local ab5 = bellname.nameOf(80, 40)
    t:eq(ab5.name, "Ab5", "A flat 5 name")
    t:eq(ab5.alter, -1, "A flat 5 alter")
  end,
  cb_keeps_its_octave = function(t)
    local cb5 = bellname.nameOf(71, 35)
    t:eq(cb5.name, "Cb5", "C flat 5 name")
    t:eq(cb5.octave, 5, "C flat 5 octave")
  end,
  b_sharp_keeps_its_octave = function(t)
    local bs3 = bellname.nameOf(60, 27)
    t:eq(bs3.name, "B#3")
    t:eq(bs3.octave, 3)
  end,
  regions = function(t)
    t:eq(bellname.regionOf(14), "bassRow2", "C2 region")
    t:eq(bellname.regionOf(20), "bassRow2", "B2 region")
    t:eq(bellname.regionOf(21), "bassRow1", "C3 region")
    t:eq(bellname.regionOf(28), "bassStaff", "C4 region")
    t:eq(bellname.regionOf(35), "bassStaff", "C5 region")
    t:eq(bellname.regionOf(36), "trebleStaff", "D5 region")
    t:eq(bellname.regionOf(49), "trebleStaff", "C7 region")
    t:eq(bellname.regionOf(50), "trebleRow1", "D7 region")
    t:eq(bellname.regionOf(57), "trebleRow2", "D8 region")
    t:eq(bellname.regionOf(63), "trebleRow2", "C9 region")
    t:eq(bellname.regionOf(13), "", "below C2 is out of range")
    t:eq(bellname.regionOf(64), "", "above C9 is out of range")
  end,
  written_to_bell_space = function(t)
    local b = bellname.fromWritten(60, 28)
    t:eq(b.pitch, 72, "middle C bell pitch")
    t:eq(b.diatonic, 35, "middle C bell diatonic")
    local d = bellname.fromWritten(62, 29)
    t:eq(d.pitch, 74, "D4 bell pitch")
    t:eq(d.diatonic, 36, "D4 bell diatonic")
    local r = bellname.toWritten(b.pitch, b.diatonic)
    t:eq(r.pitch, 60, "round trip pitch")
    t:eq(r.diatonic, 28, "round trip diatonic")
    local c = bellname.fromWritten(59, 28)
    t:eq(c.pitch, 71, "Cb bell pitch")
    t:eq(c.diatonic, 35, "Cb bell diatonic")
  end,
  from_spelling = function(t)
    local g = bellname.fromSpelling("G#5")
    t:eq(g.pitch, 80)
    t:eq(g.diatonic, 39)
    local a = bellname.fromSpelling("Ab4")
    t:eq(a.pitch, 68)
    t:eq(a.diatonic, 33)
    local low = bellname.fromSpelling("B-1")
    t:eq(low.pitch, 11)
    t:eq(low.diatonic, -1)
  end,
  doubles_round_trip = function(t)
    for _, s in ipairs({ "Fx4", "Ebb4", "G#5", "Ab4", "C2", "C9", "Cb5", "B#3" }) do
      local p = bellname.fromSpelling(s)
      t:ok(p ~= nil, s .. " parses")
      t:eq(bellname.toSpelling(p.pitch, p.diatonic), s, s .. " round trip")
    end
    t:eq(bellname.fromSpelling("Fx4").pitch, 67, "F double sharp 4 is G4's pitch")
    t:eq(bellname.fromSpelling("Ebb4").pitch, 62, "E double flat 4 is D4's pitch")
  end,
  beyond_double_accidentals = function(t)
    t:eq(bellname.nameOf(63, 28).name, "C4", "as Sibelius AccidentalText: no text beyond a double sharp")
    t:eq(bellname.toSpelling(63, 28), nil, "no spelling Dorico could take")
    t:eq(bellname.toSpelling(57, 28), nil, "nor below a double flat")
    t:eq(bellname.toSpelling(62, 28), "Cx4")
  end,
  bad_spellings = function(t)
    t:eq(bellname.fromSpelling("H4"), nil)
    t:eq(bellname.fromSpelling("C"), nil)
    t:eq(bellname.fromSpelling(""), nil)
    t:eq(bellname.fromSpelling("C#x4"), nil, "mixed accidentals are not a spelling")
  end,
  constants = function(t)
    t:eq(#constants.KINDS, 5)
    t:eq(constants.KINDS[1], "bells")
    t:eq(constants.KIND_NAME.pf, "P&F Handbells")
    t:eq(constants.KIND_NAME.whitechapel, "Whitechapel Handbells")
    t:eq(constants.LABEL_DASH, " - ")
    t:eq(constants.NO_NOTEHEAD, "(no notehead)")
    t:eq(constants.SHAPE_MATCH, "(match notehead)")
    t:eq(#constants.SHAPES, 7)
    t:eq(constants.SHAPES[5], "Inverted triangle")
    t:eq(constants.MESSAGES.noBellsFound, "No handbells or handchimes were found in this score.")
  end,
  double_sharp_written_as_two_sharps = function(t)
    t:eq(bellname.fromSpelling("F##4").pitch, 67, "F##4 reads as Fx4")
    t:eq(bellname.fromSpelling("F##4").diatonic, 31)
  end,
}
